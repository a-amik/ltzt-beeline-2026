import { useQuery } from '@tanstack/react-query'
import { Button } from '@gravity-ui/uikit'
import { loadSettingsForm } from '../../data'
import { num } from '../../lib/ui'
import { IconBolt, IconCheck, IconChat, IconShield, IconSliders, IconStar, IconWarning, IconWrench } from '../../lib/icons'
import { RECIPES } from '../settings/recipes'
import { ArtSettings } from './art'
import { Tiles } from './charts'

const SCENARIO_SUMMARY: Record<string, string> = {
  accident: 'При массовой аварии: приоритет работ, резерв бригад и оценка ущерба с учётом числа клиентов узла.',
  on_time: 'При риске опозданий: запас времени, учёт пробок по часам и проверка обещанных окон.',
  economy: 'Когда важно сократить расходы: выбор цели расчёта, старт дальних бригад и места ожидания.',
  overload: 'При перегрузке: распределение работы между бригадами, обед и ограничение работы сверх нормы.',
  traffic: 'В пятницу и часы пик: скорость по времени суток, данные о пробках и запас времени.',
  weather: 'В снег и ливень: больше времени на дорогу и запас перед обещанным окном.',
  intraday: 'При потоке новых заявок: резерв бригад, объединение событий и пересчёт при задержке.',
  stable: 'Когда нужно реже менять маршрут: закрепление ближайших визитов и ограничение сдвига времени.',
}

/**
 * Зачем в прототипе раздел «Настройки» и что он даёт в работе: каждое число
 * модели — настройка с источником, правила дня общие для всех расчётов,
 * помощник переводит слова диспетчера в набор переключателей. Счётчики
 * полей и групп берутся из той же схемы, по которой строится форма.
 */
export default function SettingsPage({ onOpen }: { onOpen: () => void }) {
  const form = useQuery({ queryKey: ['settings-form'], queryFn: loadSettingsForm, staleTime: Infinity })
  const groups = form.data?.schema ?? []
  const plain = groups.filter((g) => !g.tech)
  const fields = groups.reduce((sum, g) => sum + g.fields.length, 0)

  return (
    <article className="b-an">
      <header className="b-an-hero">
        <div className="b-an-art"><ArtSettings /></div>
        <p className="kick">О проекте · настройки расчёта</p>
        <h1>Настройки расчёта: как задаются правила плана</h1>
        <p className="lede">
          Для&nbsp;плана нужны не&nbsp;только заявки и&nbsp;адреса, но&nbsp;и&nbsp;правила: тарифы, время реакции на&nbsp;аварию, запас на&nbsp;дорогу
          и&nbsp;другие параметры. Часть чисел Билайн назвал ориентировочно, остальные команда приняла как допущения.
          Настройки собирают правила в&nbsp;одном месте: у&nbsp;каждого поля есть единица, допустимые значения и&nbsp;подсказка с&nbsp;источником.
          После сохранения правил план пересчитывается.
        </p>
        <Tiles items={[
          { value: fields ? num(fields) : '—', icon: <IconSliders />, label: 'полей в форме', note: 'числа и переключатели, от которых зависит план' },
          { value: groups.length ? String(groups.length) : '—', icon: <IconWrench />, label: 'групп', note: plain.length ? `${plain.length} — правила дня, остальные — модель расчёта` : undefined },
          { value: '0', icon: <IconCheck />, label: 'правок в коде', note: 'при изменении тарифа, нормы или запаса времени' },
          { value: String(RECIPES.length), icon: <IconChat />, label: 'готовых сценариев', note: 'BeeGPT подбирает их по описанию ситуации' },
        ]} />
      </header>

      <section id="st-why">
        <h2><span className="ic"><IconStar /></span>Зачем нужны настройки</h2>
        <p>
          План зависит от&nbsp;норм, тарифов и&nbsp;допущений, которые могут измениться после разговора с&nbsp;заказчиком.
          Команда вынесла такие значения в&nbsp;настройки и&nbsp;файл допущений, чтобы их можно было показать, сверить с&nbsp;новыми данными
          и&nbsp;изменить без доработки программы. Для&nbsp;каждого правила дня задано поле в&nbsp;форме настроек.
        </p>
        <div className="b-an-cards">
          <div><h4>Источник рядом с&nbsp;числом</h4><p>Подсказка ⓘ объясняет назначение поля и&nbsp;происхождение значения: например, оценка Билайна или допущение команды.</p></div>
          <div><h4>Изменение без доработки</h4><p>Тариф, норму дня и&nbsp;время реакции на&nbsp;аварию меняют в&nbsp;форме. После сохранения план пересчитывается.</p></div>
          <div><h4>Значения проверены</h4><p>Значения по&nbsp;умолчанию выбраны по&nbsp;замерам на&nbsp;контрольных данных. Правила, не&nbsp;давшие выигрыша, доступны, но&nbsp;выключены.</p></div>
        </div>
      </section>

      <section id="st-what">
        <h2><span className="ic"><IconSliders /></span>Что настраивается</h2>
        <p>Сервер передаёт схему полей, по&nbsp;которой строится форма. Когда в&nbsp;схему добавляют новое правило, оно появляется и&nbsp;на&nbsp;экране.</p>
        {groups.length ? (
          <table className="b-an-table st-groups">
            <thead><tr><th>Группа</th><th>Что задаёт</th><th>Полей</th></tr></thead>
            <tbody>
              {groups.map((g) => (
                <tr key={g.key}>
                  <th>{g.title}{g.tech ? <small className="b-muted"> · модель</small> : null}</th>
                  <td>{g.note ?? g.fields.slice(0, 3).map((f) => f.label).join(', ')}</td>
                  <td>{g.fields.length}</td>
                </tr>
              ))}
            </tbody>
          </table>
        ) : (
          <p className="b-muted">{form.isPending ? 'Загружаем список настроек…' : 'Не удалось загрузить список настроек.'}</p>
        )}
        <p className="b-muted">Параметры модели&nbsp;— поиск решения, риск опоздания и&nbsp;время в&nbsp;пути&nbsp;— собраны отдельно, в&nbsp;конце формы. Их меняет специалист, отвечающий за&nbsp;расчёт.</p>
      </section>

      <section id="st-rules">
        <h2><span className="ic"><IconShield /></span>Кто задаёт правила</h2>
        <p>
          Руководитель или эксперт задаёт правила на&nbsp;день. Сервер применяет их&nbsp;к&nbsp;утреннему плану, пересчётам после событий
          и&nbsp;«Живому дню». Диспетчер может менять приоритет отдельных заявок, но&nbsp;не&nbsp;общие правила для&nbsp;всех бригад.
        </p>
        <div className="b-an-cards">
          <div><h4>Общие правила на&nbsp;сервере</h4><p>Система хранит номер версии и&nbsp;время изменения. В&nbsp;форме видно, когда правила обновляли в&nbsp;последний раз.</p></div>
          <div><h4>Правки легко отменить</h4><p>Изменённые поля выделены. Каждое можно вернуть к&nbsp;значению по&nbsp;умолчанию; кнопка «Сбросить всё» возвращает все такие значения.</p></div>
          <div><h4>Результат после сохранения</h4><p>Кнопка «Сохранить и&nbsp;пересчитать» строит план по&nbsp;новым правилам. Итог дня, число бригад и&nbsp;опоздания видны в&nbsp;сводке над картой.</p></div>
        </div>
      </section>

      <section id="st-helper">
        <h2><span className="ic"><IconChat /></span>BeeGPT подбирает настройки по&nbsp;задаче</h2>
        <p>
          Руководитель может описать ситуацию обычными словами: «мало бригад, много аварий» или «клиенты жалуются на&nbsp;опоздания».
          BeeGPT подбирает готовый сценарий и&nbsp;показывает, какие значения предлагает изменить: было&nbsp;→ станет.
          Кнопка «Применить» переносит предложение в&nbsp;форму. До&nbsp;сохранения каждую правку можно отменить.
        </p>
        <table className="b-an-table">
          <thead><tr><th>Сценарий</th><th>Что предлагает BeeGPT</th></tr></thead>
          <tbody>
            {RECIPES.map((r) => <tr key={r.key}><th>{r.title}</th><td>{SCENARIO_SUMMARY[r.key] ?? r.why}</td></tr>)}
          </tbody>
        </table>
        <p className="b-muted">
          В&nbsp;прототипе BeeGPT ищет знакомые слова в&nbsp;запросе и&nbsp;подбирает заранее заданный сценарий. Он&nbsp;не&nbsp;рассчитывает маршрут сам.
        </p>
        <div className="b-an-acts"><Button view="action" size="l" onClick={onOpen}>Открыть настройки расчёта</Button></div>
      </section>

      <section id="st-prod">
        <h2><span className="ic"><IconBolt /></span>Когда настройки нужны</h2>
        <div className="b-an-cards">
          <div><h4>Сезон и&nbsp;погода</h4><p>Перед расчётом можно изменить коэффициент времени в&nbsp;пути, тип дня и&nbsp;запас на&nbsp;опоздания.</p></div>
          <div><h4>Новые условия заказчика</h4><p>Если Билайн уточнит тариф, норму или время реакции на&nbsp;аварию, руководитель изменит значение в&nbsp;форме и&nbsp;сравнит результат.</p></div>
          <div><h4>Проверка на&nbsp;событиях дня</h4><p>После изменения правил можно запустить «Живой день» с&nbsp;тем&nbsp;же набором событий и&nbsp;сравнить его с&nbsp;контрольным планом.</p></div>
          <div><h4>Дальние бригады</h4><p>Место старта и&nbsp;плата за&nbsp;выезд в&nbsp;другую зону задаются настройками. Для&nbsp;этого не&nbsp;нужна отдельная версия программы.</p></div>
          <div><h4>Цели руководителя</h4><p>Целевые показатели по&nbsp;своевременности и&nbsp;загрузке бригад задаются в&nbsp;настройках. Экран руководителя показывает отклонения.</p></div>
          <div><h4>Подбор правил</h4><p>BeeGPT предлагает готовый набор настроек по&nbsp;описанию ситуации. Руководитель видит изменения до&nbsp;сохранения.</p></div>
        </div>
      </section>

      <section id="st-limits">
        <h2><span className="ic"><IconWarning /></span>Что потребуется для&nbsp;пилота</h2>
        <ul>
          <li>Сверить с&nbsp;заказчиком допущения команды и&nbsp;ориентировочные значения из&nbsp;ответов Билайна. Источники указаны в&nbsp;подсказках к&nbsp;настройкам.</li>
          <li>Связать права доступа с&nbsp;учётной записью заказчика и&nbsp;записывать автора каждого изменения. Сейчас роль зависит от&nbsp;открытого экрана.</li>
          <li>Предусмотреть отдельные наборы правил для&nbsp;участков и&nbsp;смен. В&nbsp;прототипе правила общие для&nbsp;города.</li>
          <li>Проверить сценарии BeeGPT на&nbsp;истории дней. Сейчас он&nbsp;выбирает один из&nbsp;{RECIPES.length}&nbsp;сценариев по&nbsp;ключевым словам.</li>
        </ul>
      </section>
    </article>
  )
}
