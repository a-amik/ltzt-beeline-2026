/** Снимок экрана с подписью; полный размер — по ссылке. */
function Shot({ src, alt, title, note, phone }: { src: string; alt: string; title: string; note: string; phone?: boolean }) {
  return (
    <figure className={`b-an-shot${phone ? ' phone' : ''}`}>
      <a href={src} target="_blank" rel="noreferrer"><img src={src} alt={alt} loading="lazy" decoding="async" /></a>
      <figcaption><b>{title}</b>{note}</figcaption>
    </figure>
  )
}

