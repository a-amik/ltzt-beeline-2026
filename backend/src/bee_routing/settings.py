@lru_cache(maxsize=1)
def _base() -> dict:
    """Настройки из допущений: то, что действует без переопределений."""
    try:
        conf = load_assumptions()
    except FileNotFoundError:
        conf = {}

    def clean(value):
        if isinstance(value, dict):
            return {k: clean(v) for k, v in value.items() if not k.startswith("_")}
        return value

    return {
        "options": dict(DEFAULT_OPTIONS),
        "economy": clean(conf.get("economy", {})),
        "breaks": clean(conf.get("breaks", {})),
        "travel": clean(conf.get("travel", {})),
    }


def _fields() -> dict[str, dict]:
    return {field["path"]: field for group in SCHEMA for field in group["fields"]}


def _get(tree: dict, path: str):
    node = tree
    for part in path.split("."):
        if not isinstance(node, dict) or part not in node:
            return None
        node = node[part]
    return node


def _set(tree: dict, path: str, value) -> None:
    parts = path.split(".")
    node = tree
    for part in parts[:-1]:
        node = node.setdefault(part, {})
    node[parts[-1]] = value


