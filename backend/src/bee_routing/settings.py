"""Настройки расчёта из интерфейса: тарифы, обед, скорости и что учитывать при построении.

Зачем. Числа модели живут в `data/assumptions.json`, и диспетчер должен
иметь возможность их поменять и сразу увидеть, как изменился план: поднять
бонус и посмотреть, сколько заявок ушло из неназначенных; запретить машину
и посмотреть, сколько стало дороги. Поэтому запрос плана несёт с собой
переопределения, а модули модели (`economy`, `travel`, `solver`) читают
числа через этот модуль, а не из файла напрямую.

Схема полей (`SCHEMA`) лежит здесь же и отдаётся клиенту: форму настроек
интерфейс строит по ней, подписи и единицы приходят готовыми. Второго
места, где перечислены настраиваемые числа, в проекте быть не должно.

Три вещи, которые нельзя ломать:

1. **Переопределение живёт ровно один запрос.** Оно ставится контекстной
   переменной на время расчёта (`use`) и снимается после; параллельные
   запросы с разными настройками не видят чужих чисел.
2. **План помнит свои настройки** (`Plan.settings`): пересчёт после события
   и ручная замена идут с теми же числами, с какими план построен.
3. **Незнакомый ключ отбрасывается, число обрезается диапазоном схемы.**
   Настройки приходят от клиента и в решатель попадают только проверенными.
4. **Общие правила задаёт руководитель, а не диспетчер** (с 25.09.2026).
   Правила дня — порядок целей, приоритеты, тарифы, вес аварии, бригады,
   правила пересчёта — лежат на сервере (`set_rules`, `PUT /rules` с ролью
   руководителя) и ложатся под каждый расчёт (`for_role`). От экрана
   диспетчера сервер берёт только оперативное: ручной приоритет заявок
   (`requests`) и бюджет поиска (`options.time_limit_s`); прочее, что он
   прислал, отбрасывается. Запрос без роли — тесты, замер, скрипты — считает
   с присланным поверх правил, как считал до разделения.
"""

