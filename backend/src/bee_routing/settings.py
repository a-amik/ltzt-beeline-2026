ROLES = ("dispatcher", "manager")
# Что диспетчер вправе прислать сам: оперативное по заявкам и сколько ждать решателя.
DISPATCHER_KEYS = ("requests",)
DISPATCHER_PATHS = ("options.time_limit_s",)

_rules: dict = {}
_rules_meta: dict = {"version": 0, "updated_at": None}


def rules() -> dict:
    """Общие правила дня и их версия: переопределения поверх допущений."""
    return {"rules": deepcopy(_rules), **_rules_meta}


def set_rules(raw: dict | None, updated_at: str | None = None, version: int | None = None) -> dict:
    """Заменить общие правила дня целиком: проверенные схемой, без оперативного диспетчера."""
    global _rules
    clean = sanitize(raw)
    clean.pop("requests", None)
    _rules = clean
    _rules_meta["version"] = int(version) if version is not None else _rules_meta["version"] + 1
    _rules_meta["updated_at"] = updated_at
    return rules()


def clear_rules() -> None:
    """Правила по допущениям, версия с нуля — для тестов и чистого старта."""
    global _rules
    _rules = {}
    _rules_meta.update(version=0, updated_at=None)


def _deep_merge(base: dict, over: dict) -> dict:
    out = deepcopy(base)
    for key, value in over.items():
        if isinstance(value, dict) and isinstance(out.get(key), dict):
            out[key] = _deep_merge(out[key], value)
        else:
            out[key] = deepcopy(value)
    return out


def for_role(raw: dict | None, role: str | None) -> dict:
    """Настройки расчёта с общими правилами под ними.

    Диспетчер: правила целиком, а из присланного — только `DISPATCHER_KEYS`
    и `DISPATCHER_PATHS`. Руководитель и запрос без роли: присланное поверх
    правил.
    """
    raw = raw if isinstance(raw, dict) else {}
    if role != "dispatcher":
        return _deep_merge(_rules, raw)
    out = deepcopy(_rules)
    for key in DISPATCHER_KEYS:
        if key in raw:
            out[key] = deepcopy(raw[key])
    for path in DISPATCHER_PATHS:
        value = _get(raw, path)
        if value is not None:
            _set(out, path, value)
    return out


def current() -> dict:
    """Проверенные переопределения текущего запроса — чтобы положить их в план."""
    return deepcopy(_current.get() or {})


def effective_engineers(engineers: list[Engineer]) -> list[Engineer]:
    """Бригады с учётом настроек: разрешённые виды транспорта и согласие на нагрузку.

    Вид транспорта, запрещённый настройкой, из набора бригады убирается.
    Если у бригады ничего не осталось, она ходит пешком: без транспорта
    бригада не может даже дойти до первой заявки.
    """
    modes = option("modes") or MODES
    allow_extra = bool(option("extra_load"))
    crews = (_current.get() or {}).get("crews", {})
    out = []
    for eng in engineers:
        copy = eng.model_copy(deep=True)
        own = crews.get(eng.id, {})
        if "home" in own:
            copy.home = Point(lat=own["home"]["lat"], lon=own["home"]["lon"])
        elif copy.anchor is not None and option("zone_start_point") == "anchor":
            # Дальняя бригада стартует из опорной точки своего района, а не из центра своих визитов.
            copy.home = copy.anchor.model_copy()
        if "transports" in own:
            copy.transports = [Transport(t) for t in own["transports"]]
        if "extra_load" in own:
            copy.extra_load = bool(own["extra_load"])
        kept = [t for t in copy.transports if t.value in modes] or [Transport.FOOT]
        copy.transports = kept
        copy.transport = kept[0]
        copy.extra_load = copy.extra_load and allow_extra
        out.append(copy)
    return out
