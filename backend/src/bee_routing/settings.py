PRIORITY_LEVELS = ("urgent", "high", "low")
SEGMENT_LEVELS = ("KA", "A", "B", "C", "D")


def sanitize_requests(raw) -> dict:
    """Ручной приоритет заявок из интерфейса: «заявка → уровень».

    Уровни: `urgent` — как срочная (вне очереди, ставится директивно, цена
    пропуска с коэффициентом срочной); `high` — ступенью выше своей;
    `low` — берётся последней. Обычный уровень не хранится.

    Там же сегмент клиента аварии (`segment`: KA, A, B, C, D), если диспетчер
    знает клиента лучше синтетики (`segments.py`).
    """
    out: dict = {}
    if not isinstance(raw, dict):
        return out
    for rid, fields in list(raw.items())[:500]:
        if not isinstance(rid, str) or not isinstance(fields, dict):
            continue
        own = {}
        if fields.get("priority") in PRIORITY_LEVELS:
            own["priority"] = fields["priority"]
        if fields.get("segment") in SEGMENT_LEVELS:
            own["segment"] = fields["segment"]
        if own:
            out[rid[:64]] = own
    return out


def manual_priority(request_id: str) -> str | None:
    """Уровень, который диспетчер поставил заявке руками; `None` — обычный."""
    own = (_current.get() or {}).get("requests", {}).get(request_id)
    return own.get("priority") if own else None


def manual_segment(request_id: str) -> str | None:
    """Сегмент клиента аварии, который диспетчер поставил руками; `None` — синтетика или из набора."""
    own = (_current.get() or {}).get("requests", {}).get(request_id)
    return own.get("segment") if own else None


def is_urgent(request) -> bool:
    """Срочная по данным или по ручному приоритету диспетчера."""
    return request.priority.value == "urgent" or manual_priority(request.id) == "urgent"


def sanitize_crews(raw) -> dict:
    """Настройки бригад из интерфейса: дом, набор транспорта, согласие на нагрузку.

    Схемой не описываются — бригад в регионе дюжина, и у каждой свой набор
    полей. Принимается словарь «бригада → поля», лишнее отбрасывается.
    """
    out: dict = {}
    if not isinstance(raw, dict):
        return out
    for eng_id, fields in raw.items():
        if not isinstance(fields, dict) or not isinstance(eng_id, str):
            continue
        clean: dict = {}
        home = fields.get("home")
        if isinstance(home, dict):
            try:
                lat, lon = float(home["lat"]), float(home["lon"])
                if 54 <= lat <= 57 and 35 <= lon <= 40:
                    clean["home"] = {"lat": round(lat, 6), "lon": round(lon, 6)}
                    if isinstance(home.get("address"), str):
                        clean["home"]["address"] = home["address"][:200]
            except (KeyError, TypeError, ValueError):
                pass
        transports = fields.get("transports")
        if isinstance(transports, list):
            kept = [t for t in MODES if t in transports]
            if kept:
                clean["transports"] = kept
        if "extra_load" in fields:
            clean["extra_load"] = bool(fields["extra_load"])
        if clean:
            out[eng_id] = clean
    return out


def sanitize(raw: dict | None) -> dict:
    """Оставить из присланного только поля схемы, приведя типы и диапазоны."""
    out: dict = {}
    if not raw:
        return out
    crews = sanitize_crews(raw.get("crews"))
    if crews:
        out["crews"] = crews
    manual = sanitize_requests(raw.get("requests"))
    if manual:
        out["requests"] = manual
    for path, field in _fields().items():
        value = _get(raw, path)
        if value is None:
            continue
        kind = field["type"]
        try:
            if kind == "bool":
                value = bool(value)
            elif kind == "number":
                value = float(value)
                value = min(float(field["max"]), max(float(field["min"]), value))
                if float(field["step"]).is_integer():
                    value = round(value)
            elif kind == "choice":
                allowed = {c["value"] for c in field["choices"]}
                if value not in allowed:
                    continue
            elif kind == "multi":
                allowed = [c["value"] for c in field["choices"]]
                value = [v for v in allowed if v in list(value)]
            elif kind == "time":
                hours, _, minutes = str(value).partition(":")
                h, m = int(hours), int(minutes or 0)
                if not (0 <= h < 24 and 0 <= m < 60):
                    continue
                value = f"{h:02d}:{m:02d}"
        except (TypeError, ValueError):
            continue
        _set(out, path, value)
    return out


def defaults() -> dict:
    """Действующие по умолчанию значения всех полей схемы."""
    out: dict = {}
    base = _base()
    for path in _fields():
        value = _get(base, path)
        if value is not None:
            _set(out, path, deepcopy(value))
    return out


def _merge(override: dict | None) -> dict:
    tree = deepcopy(_base())
    if override:
        for path in _fields():
            value = _get(override, path)
            if value is not None:
                _set(tree, path, deepcopy(value))
    return tree


@lru_cache(maxsize=1)
def _default_tree() -> dict:
    return _merge(None)


def merged() -> dict:
    """Настройки текущего запроса поверх допущений. Словарь общий — не менять."""
    return _tree.get() or _default_tree()


def section(name: str) -> dict:
    """Одна группа настроек текущего запроса: options, economy, breaks, travel."""
    return merged().get(name, {})


def option(name: str):
    """Одна опция построения."""
    return section("options").get(name, DEFAULT_OPTIONS.get(name))


def zone_start_km() -> float:
    """Порог удалённого подучастка из допущений (`engineers.zone_start_km`)."""
    try:
        return float(load_assumptions().get("engineers", {}).get("zone_start_km", 40))
    except FileNotFoundError:
        return 40.0


@contextmanager
def use(settings: dict | None) -> Iterator[dict]:
    """Посчитать внутри блока с настройками из запроса."""
    clean = sanitize(settings)
    token = _current.set(clean)
    tree_token = _tree.set(_merge(clean))
    try:
        yield clean
    finally:
        _tree.reset(tree_token)
        _current.reset(token)


