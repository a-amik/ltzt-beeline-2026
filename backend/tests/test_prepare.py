"""Нормализация адресов: сырьё написано неровно, а вид должен быть один."""

import pytest

from bee_routing.prepare import hhmm, normalize_address, translit


@pytest.mark.parametrize(
    ("raw", "expected"),
    [
        ("Город Москва, пр-кт.Волгоградский, д. 131 к 4, кв. 1", "Москва, Волгоградский проспект, 131к4"),
        ("г.Город Москва, наб.Семеновская, д. 7/3", "Москва, Семеновская набережная, 7/3"),
        ("Москва Булатниковский пр-зд. д. 14к3", "Москва, Булатниковский проезд, 14к3"),
        ("Домодедово, проезд.Советский 1-й, д. 9А, кв. 44", "Московская область, Домодедово, 1-й Советский проезд, 9А"),
        ("МО, г. Кашира Центральная ул. д. 17", "Московская область, Кашира, Центральная улица, 17"),
        (
            "обл.Московская область, г.Домодедово, пгт.Востряково-1, ул.Жуковского, д. 14/18",
            "Московская область, Домодедово, Востряково-1, Жуковского улица, 14/18",
        ),
        ("Город Москва, ул.Земляной Вал, д. 38/40 стр. 2, кв. 75", "Москва, Земляной Вал улица, 38/40с2"),
        ("г. Москва, ул Юных Ленинцев, д 83с 4", "Москва, Юных Ленинцев улица, 83с4"),
    ],
)
def test_normalize_address(raw, expected):
    """Каждый из встреченных в данных видов приводится к одному."""
    assert normalize_address(raw) == expected


def test_apartment_dropped():
    """Квартира в адрес не входит: геокодеру она не нужна, сшивке мешает."""
    with_flat = normalize_address("Город Москва, ул.Окская, д. 5, кв. 42")
    without = normalize_address("Город Москва, ул.Окская, д. 5")
    assert with_flat == without == "Москва, Окская улица, 5"


def test_translit():
    """Идентификатор бригады — транслит фамилии."""
    assert translit("Смоленский") == "smolensky"
    assert translit("Лебедев") == "lebedev"
    assert translit("Коваль") == "koval"
    assert translit("Кузьмин") == "kuzmin"


def test_hhmm():
    """Из даты со временем остаётся только время."""
    assert hhmm("17.08.2026 20:00") == "20:00"
    assert hhmm("17.08.2026 0:01") == "00:01"
